// Package netboot runs one dnsmasq per lab, as a systemd transient unit,
// serving DHCP on the lab's DHCP networks and TFTP for network boot:
// UEFI firmware gets iPXE, iPXE gets boot.ipxe, which boots the declared
// kernel and initrd (or runs a custom script).
package netboot

import (
	"context"
	"fmt"
	"net/netip"
	"os"
	"path"
	"path/filepath"
	"strings"
	"time"

	"bmbox/pkg/systemd"
)

const (
	EnvDnsmasq = "BMBOX_DNSMASQ"
	EnvIPXE    = "BMBOX_IPXE"

	// Names in the TFTP root.
	IPXEName   = "ipxe.efi"
	ScriptName = "boot.ipxe"
	KernelName = "vmlinuz"
	InitrdName = "initrd"

	leaseTime = "1h"
)

// IPXECandidates are where distributions install the iPXE UEFI binary.
// snponly drives the NIC through the firmware's own driver, which is what
// OVMF provides for virtio-net.
var IPXECandidates = []string{
	"/usr/lib/ipxe/snponly.efi",               // Debian, Ubuntu
	"/usr/share/ipxe/ipxe-snponly-x86_64.efi", // Fedora, RHEL
	"/usr/lib/ipxe/ipxe.efi",
	"/usr/share/ipxe/ipxe-x86_64.efi",
	"/usr/share/ipxe/x86_64/ipxe.efi", // Arch
}

// Network is a lab network served by the lab's dnsmasq.
type Network struct {
	Name    string
	Bridge  string
	Gateway netip.Prefix
	First   netip.Addr
	Last    netip.Addr
}

// Host pins a hostname, and optionally an address, to a MAC.
type Host struct {
	MAC  string
	Name string
	IP   netip.Addr // zero: dynamic
}

// Boot is what nodes netboot. Paths are on the host; http(s) URLs are
// fetched by iPXE directly.
type Boot struct {
	Kernel  string
	Initrd  string
	Cmdline string
	Script  string
}

type Spec struct {
	Lab      string
	Unit     string
	Dir      string // dnsmasq.conf, leases and the TFTP root
	Networks []Network
	Hosts    []Host
	Boot     *Boot // nil: addresses only
}

func (s Spec) ConfigFile() string { return filepath.Join(s.Dir, "dnsmasq.conf") }
func (s Spec) LeaseFile() string  { return filepath.Join(s.Dir, "dnsmasq.leases") }
func (s Spec) TFTPRoot() string   { return filepath.Join(s.Dir, "tftp") }

// Description marks the unit as the lab's, for discovery.
func Description(lab string) string { return "bmbox dnsmasq for " + lab }

// Tools are the external programs netboot is built on.
type Tools struct {
	Dnsmasq string
	IPXE    string
}

// FindTools locates dnsmasq (explicit path, $BMBOX_DNSMASQ, PATH, /usr/sbin)
// and, when needed, the iPXE UEFI binary (explicit, $BMBOX_IPXE, then
// IPXECandidates).
func FindTools(dnsmasq, ipxe string, needIPXE bool) (Tools, error) {
	var t Tools
	t.Dnsmasq = firstExisting(dnsmasq, os.Getenv(EnvDnsmasq))
	if t.Dnsmasq == "" {
		for _, p := range []string{"/usr/sbin/dnsmasq", "/usr/bin/dnsmasq"} {
			if _, err := os.Stat(p); err == nil {
				t.Dnsmasq = p
				break
			}
		}
	}
	if t.Dnsmasq == "" {
		return t, fmt.Errorf("DHCP needs dnsmasq: not found (install dnsmasq or dnsmasq-base, or set %s=/path/to/dnsmasq)", EnvDnsmasq)
	}
	if !needIPXE {
		return t, nil
	}
	t.IPXE = firstExisting(ipxe, os.Getenv(EnvIPXE))
	if t.IPXE == "" {
		for _, p := range IPXECandidates {
			if _, err := os.Stat(p); err == nil {
				t.IPXE = p
				break
			}
		}
	}
	if t.IPXE == "" {
		return t, fmt.Errorf("netboot needs the iPXE UEFI binary: not found in %s (install ipxe, or set %s=/path/to/snponly.efi)",
			strings.Join(IPXECandidates, ", "), EnvIPXE)
	}
	return t, nil
}

func firstExisting(paths ...string) string {
	for _, p := range paths {
		if p != "" {
			if _, err := os.Stat(p); err == nil {
				return p
			}
		}
	}
	return ""
}

// Config renders the lab's dnsmasq configuration.
func Config(s Spec) string {
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }
	w("# Generated by bmbox for lab %s. Do not edit.", s.Lab)
	w("port=0") // no DNS
	// Only the lab bridges. bind-interfaces also lets this dnsmasq share
	// port 67 with others bound the same way (libvirt, Ironic).
	w("bind-interfaces")
	for _, n := range s.Networks {
		w("interface=%s", n.Bridge)
	}
	w("user=nobody")
	w("log-facility=-")
	w("dhcp-authoritative")
	w("dhcp-leasefile=%s", s.LeaseFile())
	for _, n := range s.Networks {
		w("dhcp-range=set:%s,%s,%s,%s,%s", n.Name, n.First, n.Last, prefixMask(n.Gateway.Bits()), leaseTime)
	}
	for _, h := range s.Hosts {
		if h.IP.IsValid() {
			w("dhcp-host=%s,%s,%s", h.MAC, h.IP, h.Name)
		} else {
			w("dhcp-host=%s,%s", h.MAC, h.Name)
		}
	}
	// TFTP also answers bmbox's readiness probe when nothing is netbooted.
	w("enable-tftp")
	w("tftp-root=%s", s.TFTPRoot())
	if s.Boot != nil {
		w("dhcp-match=set:efi64,option:client-arch,7")
		w("dhcp-match=set:efi64,option:client-arch,9")
		w("dhcp-userclass=set:ipxe,iPXE")
		w("dhcp-boot=tag:ipxe,%s", ScriptName)
		w("dhcp-boot=tag:!ipxe,tag:efi64,%s", IPXEName)
	}
	return b.String()
}

func prefixMask(bits int) string {
	m := uint32(0xffffffff) << (32 - bits)
	return fmt.Sprintf("%d.%d.%d.%d", m>>24, m>>16&0xff, m>>8&0xff, m&0xff)
}

func isURL(s string) bool {
	return strings.HasPrefix(s, "http://") || strings.HasPrefix(s, "https://")
}

// Script renders boot.ipxe. A local custom script is served as is and has
// no generated form.
func Script(lab string, b Boot) []byte {
	var s strings.Builder
	s.WriteString("#!ipxe\n")
	fmt.Fprintf(&s, "# Generated by bmbox for lab %s.\n", lab)
	if b.Script != "" {
		fmt.Fprintf(&s, "chain %s\n", b.Script)
		return []byte(s.String())
	}
	kernel, initrd := KernelName, InitrdName
	if isURL(b.Kernel) {
		kernel = b.Kernel
	}
	if isURL(b.Initrd) {
		initrd = b.Initrd
	}
	args := b.Cmdline
	if b.Initrd != "" {
		// EFI-stub kernels find the initrd by its name in iPXE's file
		// system, which is the last component of its URL.
		args = strings.TrimSpace("initrd=" + path.Base(initrd) + " " + args)
	}
	fmt.Fprintf(&s, "echo bmbox: booting %s\n", kernel)
	fmt.Fprintf(&s, "kernel %s\n", strings.TrimSpace(kernel+" "+args))
	if b.Initrd != "" {
		fmt.Fprintf(&s, "initrd %s\n", initrd)
	}
	s.WriteString("boot\n")
	return []byte(s.String())
}

// tftpFile is a file the TFTP root must hold: copied from From, or Data.
type tftpFile struct {
	From string
	Data []byte
}

// tftpFiles lists the TFTP root's content for a spec.
func tftpFiles(s Spec, ipxe string) map[string]tftpFile {
	files := map[string]tftpFile{}
	b := s.Boot
	if b == nil {
		return files
	}
	files[IPXEName] = tftpFile{From: ipxe}
	switch {
	case b.Script != "" && !isURL(b.Script):
		files[ScriptName] = tftpFile{From: b.Script}
	default:
		files[ScriptName] = tftpFile{Data: Script(s.Lab, *b)}
	}
	if b.Kernel != "" && !isURL(b.Kernel) {
		files[KernelName] = tftpFile{From: b.Kernel}
	}
	if b.Initrd != "" && !isURL(b.Initrd) {
		files[InitrdName] = tftpFile{From: b.Initrd}
	}
	return files
}

// syncTFTP makes the TFTP root hold exactly files. Copies are skipped when
// size and modification time already match the source. The root is
// world-readable because dnsmasq serves it as "nobody".
func syncTFTP(root string, files map[string]tftpFile) error {
	if err := os.MkdirAll(root, 0o755); err != nil {
		return err
	}
	if err := os.Chmod(root, 0o755); err != nil {
		return err
	}
	entries, err := os.ReadDir(root)
	if err != nil {
		return err
	}
	for _, e := range entries {
		if _, ok := files[e.Name()]; !ok {
			if err := os.RemoveAll(filepath.Join(root, e.Name())); err != nil {
				return err
			}
		}
	}
	for name, f := range files {
		dst := filepath.Join(root, name)
		if f.From == "" {
			if old, err := os.ReadFile(dst); err == nil && string(old) == string(f.Data) {
				continue
			}
			if err := writeAtomic(dst, f.Data, time.Time{}); err != nil {
				return err
			}
			continue
		}
		src, err := os.Stat(f.From)
		if err != nil {
			return fmt.Errorf("netboot: %w", err)
		}
		if !src.Mode().IsRegular() {
			return fmt.Errorf("netboot: %s is not a regular file", f.From)
		}
		if dst, err := os.Stat(dst); err == nil && dst.Size() == src.Size() && dst.ModTime().Equal(src.ModTime()) {
			continue
		}
		data, err := os.ReadFile(f.From)
		if err != nil {
			return fmt.Errorf("netboot: %w", err)
		}
		if err := writeAtomic(dst, data, src.ModTime()); err != nil {
			return err
		}
	}
	return nil
}

func writeAtomic(path string, data []byte, mtime time.Time) error {
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, data, 0o644); err != nil {
		return err
	}
	if err := os.Chmod(tmp, 0o644); err != nil {
		return err
	}
	if !mtime.IsZero() {
		if err := os.Chtimes(tmp, mtime, mtime); err != nil {
			return err
		}
	}
	return os.Rename(tmp, path)
}

// Manager runs the lab's dnsmasq through systemd.
type Manager struct {
	sd    *systemd.Manager
	tools Tools
}

func NewManager(sd *systemd.Manager, tools Tools) *Manager {
	return &Manager{sd: sd, tools: tools}
}

type Result struct {
	Started bool
}

// Ensure writes the config and TFTP root and makes sure dnsmasq serves
// them. A running dnsmasq whose config did not change is left alone (TFTP
// files are read per request).
func (m *Manager) Ensure(ctx context.Context, s Spec) (*Result, error) {
	if len(s.Networks) == 0 {
		return nil, fmt.Errorf("netboot: no DHCP network")
	}
	if err := os.MkdirAll(s.Dir, 0o755); err != nil {
		return nil, err
	}
	if err := syncTFTP(s.TFTPRoot(), tftpFiles(s, m.tools.IPXE)); err != nil {
		return nil, err
	}
	cfg := []byte(Config(s))
	changed := true
	if old, err := os.ReadFile(s.ConfigFile()); err == nil && string(old) == string(cfg) {
		changed = false
	}
	if changed {
		if err := writeAtomic(s.ConfigFile(), cfg, time.Time{}); err != nil {
			return nil, err
		}
	}
	if !changed && m.sd.State(ctx, s.Unit) == "active" {
		return &Result{}, nil
	}
	if err := m.sd.Start(ctx, systemd.Service{
		Unit:        s.Unit,
		Description: Description(s.Lab),
		Cmd:         []string{m.tools.Dnsmasq, "--keep-in-foreground", "--conf-file=" + s.ConfigFile()},
	}); err != nil {
		return nil, err
	}
	if err := m.waitReady(ctx, s); err != nil {
		return nil, err
	}
	return &Result{Started: true}, nil
}

// waitReady waits until dnsmasq answers TFTP on the first network: it
// sets up every socket (DHCP included) before serving, and exits if one
// fails.
func (m *Manager) waitReady(ctx context.Context, s Spec) error {
	addr := netip.AddrPortFrom(s.Networks[0].Gateway.Addr(), 69)
	deadline := time.Now().Add(15 * time.Second)
	var last error
	for time.Now().Before(deadline) {
		if last = ProbeTFTP(addr, ScriptName, time.Second); last == nil {
			return nil
		}
		select {
		case <-ctx.Done():
			return ctx.Err()
		case <-time.After(300 * time.Millisecond):
		}
	}
	return fmt.Errorf("dnsmasq for lab %s did not become ready (%v); see: journalctl -u %s", s.Lab, last, s.Unit)
}
