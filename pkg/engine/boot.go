package engine

import (
	"context"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/the-daonm/bmbox/pkg/systemd"
	"github.com/the-daonm/bmbox/pkg/topology"
	"github.com/the-daonm/bmbox/pkg/workspace"
)

// Bridges, firewall rules, sysctls, serial sockets and the BMC and dnsmasq
// units do not survive a reboot of the host; domains, disks and the pool
// do. A boot unit runs `bmbox up --lab <lab>` from the topology snapshot
// to bring the rest back. It runs before libvirt-guests, so guests that
// service restores find their bridges.

// BootUnit is the persistent unit that brings a lab back at boot.
func BootUnit(lab string) string { return "bmbox-" + lab + "-boot.service" }

// bootUnitContent renders the boot unit of a lab, running bin.
func bootUnitContent(lab, bin, libvirtURI string, ws *workspace.Workspace) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by bmbox. Do not edit: up rewrites it, destroy removes it.\n")
	fmt.Fprintf(&b, "[Unit]\n")
	fmt.Fprintf(&b, "Description=bmbox boot for %s\n", lab)
	fmt.Fprintf(&b, "Wants=network-online.target\n")
	fmt.Fprintf(&b, "After=network-online.target libvirtd.service virtqemud.service firewalld.service docker.service\n")
	fmt.Fprintf(&b, "Before=libvirt-guests.service\n\n")
	fmt.Fprintf(&b, "[Service]\n")
	fmt.Fprintf(&b, "Type=oneshot\n")
	fmt.Fprintf(&b, "RemainAfterExit=yes\n")
	if ws.Root != workspace.SystemRoot {
		fmt.Fprintf(&b, "Environment=%s=%s\n", workspace.EnvHome, systemdQuote(ws.Root))
	}
	fmt.Fprintf(&b, "ExecStart=%s up --lab %s --connect %s\n", systemdQuote(bin), lab, systemdQuote(libvirtURI))
	fmt.Fprintf(&b, "\n[Install]\n")
	fmt.Fprintf(&b, "WantedBy=multi-user.target\n")
	return b.String()
}

// systemdQuote quotes a value for a unit file when it needs it.
func systemdQuote(s string) string {
	if !strings.ContainsAny(s, " \t\"'\\%$") {
		return s
	}
	r := strings.NewReplacer(`\`, `\\`, `"`, `\"`, `%`, `%%`, `$`, `$$`)
	return `"` + r.Replace(s) + `"`
}

// ensureBootUnit installs or removes the lab's boot unit as the topology
// asks.
func ensureBootUnit(ctx context.Context, t *topology.Topology, sd *systemd.Manager, ws *workspace.Workspace,
	opt Options, log func(string, ...any)) error {
	lab := t.Metadata.Name
	unit := BootUnit(lab)
	log("==> Boot")
	if !t.Spec.AutostartEnabled() {
		removed, err := sd.RemoveUnit(ctx, unit)
		if err != nil {
			return err
		}
		if removed {
			log("    autostart  removed %s", unit)
		} else {
			log("    autostart  off")
		}
		return nil
	}
	bin, err := os.Executable()
	if err != nil {
		return fmt.Errorf("locate the bmbox binary for %s: %w", unit, err)
	}
	if bin, err = filepath.EvalSymlinks(bin); err != nil {
		return err
	}
	changed, err := sd.InstallUnit(ctx, unit, bootUnitContent(lab, bin, opt.LibvirtURI, ws))
	if err != nil {
		return err
	}
	action := "enabled"
	if changed {
		action = "installed"
	}
	log("    autostart  %s %s (runs %s up --lab %s at boot)", action, unit, bin, lab)
	return nil
}
